// Generates lib/tech-icons.ts: brand marks (from simple-icons) for every technology
// named in lib/data.ts and lib/profile.ts, so the client bundle only carries the icons we use.
// Run with: node scripts/gen-tech-icons.mjs
import { readFileSync, writeFileSync } from "node:fs";
import * as si from "simple-icons";

const bySlug = new Map(Object.values(si).filter((i) => i && i.slug).map((i) => [i.slug, i]));

// Names whose simple-icons slug can't be derived mechanically.
const aliases = {
  "apache airflow": "apacheairflow",
  airflow: "apacheairflow",
  "google gemini": "googlegemini",
  "gemini live api": "googlegemini",
  "expo react native": "expo",
  "react native": "react",
  "huggingface spaces": "huggingface",
  "pytorch ddp": "pytorch",
  torchvision: "pytorch",
  "docker compose": "docker",
  "shadcn ui": "shadcnui",
  "radix ui": "radixui",
  "framer motion": "framer",
  "google maps api": "googlemaps",
  pyspark: "apachespark",
  "apache spark": "apachespark",
  "scikit-learn": "scikitlearn",
  "next.js": "nextdotjs",
  "node.js": "nodedotjs",
  "three.js": "threedotjs",
  "cytoscape.js": "cytoscapedotjs",
  "vue.js": "vuedotjs",
  "tailwind css": "tailwindcss",
};

const base = (name) =>
  name
    .toLowerCase()
    .replace(/\(.*?\)/g, "")
    .replace(/\s+\d[\d.]*$/, "")
    .trim();

const resolve = (name) => {
  const b = base(name);
  const slug = aliases[b] ?? b.replace(/\./g, "dot").replace(/[^a-z0-9]/g, "");
  return bySlug.get(slug);
};

const sources = ["lib/data.ts", "lib/profile.ts"].map((f) => readFileSync(f, "utf8")).join("\n");
const names = new Set();
for (const m of sources.matchAll(/(?:technologies|tags|skills|stack): \[([^\]]*)\]/g)) {
  for (const s of m[1].matchAll(/"([^"]+)"/g)) names.add(s[1]);
}

const icons = {};
const keys = {};
for (const n of [...names].sort()) {
  const icon = resolve(n);
  if (!icon) continue;
  icons[icon.slug] = { path: icon.path, hex: icon.hex };
  keys[base(n)] = icon.slug;
}

writeFileSync(
  "lib/tech-icons.ts",
  `// Generated by scripts/gen-tech-icons.mjs from simple-icons (CC0). Do not edit by hand.\n\n` +
    `export const techSlugs: Record<string, string> = ${JSON.stringify(keys, null, 2)};\n\n` +
    `export const techIcons: Record<string, { path: string; hex: string }> = ${JSON.stringify(icons, null, 2)};\n\n` +
    `export const techKey = (name: string) =>\n  name\n    .toLowerCase()\n    .replace(/\\(.*?\\)/g, "")\n    .replace(/\\s+\\d[\\d.]*$/, "")\n    .trim();\n`,
);
console.log(`${Object.keys(icons).length} icons covering ${Object.keys(keys).length} of ${names.size} names`);
